android {
  namespace = "com.aistudio.naiklevel.bmedkq"
  compileSdk = 36

  defaultConfig {
    applicationId = "com.aistudio.naiklevel.bmedkq"
    minSdk = 24
    targetSdk = 36
    versionCode = 1
    versionName = "1.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

    // Membaca konfigurasi dari .env atau environment variable.
    val localEnv = Properties().apply {
      val f = rootProject.file(".env")
      if (f.exists()) {
        f.inputStream().use { load(it) }
      }
    }

    fun envValue(key: String, default: String = ""): String =
      (localEnv.getProperty(key) ?: System.getenv(key) ?: default)
        .trim()
        .replace("\"", "")

    buildConfigField(
      "String",
      "GOOGLE_WEB_CLIENT_ID",
      "\"${envValue("GOOGLE_WEB_CLIENT_ID", "")}\""
    )

    buildConfigField(
      "String",
      "AI_MODEL_NAME",
      "\"${envValue("AI_MODEL_NAME", "gemini-3.8-flash")}\""
    )
  }

  // Konfigurasi signing release.
  signingConfigs {
    create("release") {
      val keystorePath =
        System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"

      storeFile = file(keystorePath)
      storePassword = System.getenv("STORE_PASSWORD")
      keyAlias = "upload"
      keyPassword = System.getenv("KEY_PASSWORD")
    }

    create("debugConfig") {
      val customDebugKeystore = file("${rootDir}/debug.keystore")

      if (customDebugKeystore.exists()) {
        storeFile = customDebugKeystore
        storePassword = "android"
        keyAlias = "androiddebugkey"
        keyPassword = "android"
      }
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false

      proguardFiles(
        getDefaultProguardFile("proguard-android-optimize.txt"),
        "proguard-rules.pro"
      )

      signingConfig = signingConfigs.getByName("release")
    }

    debug {
      val custom = signingConfigs.getByName("debugConfig")

      if (custom.storeFile != null) {
        signingConfig = custom
      }
    }
  }

  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }

  buildFeatures {
    compose = true
    buildConfig = true
  }

  testOptions {
    unitTests {
      isIncludeAndroidResources = true
    }
  }

  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}

